/**
 * Writes shopify/snippets/headless-redirect.liquid, the snippet that sends
 * every page of the Shopify Online Store theme to this storefront.
 *
 * Why: Shopify's checkout links its logo, "return to cart" and "continue
 * shopping" to the shop's primary domain, which serves the Online Store
 * theme. That link is not configurable in checkout; the theme, however, is
 * ours to change. See docs/SHOPIFY-VERCEL.md, "Rediriger le checkout".
 *
 * The target comes from BRAND.siteUrl (app/config/brand.ts). Re-run after
 * changing it:  npm run shopify:redirect
 */
import {mkdir, writeFile} from 'node:fs/promises';
import {BRAND} from '../app/config/brand.ts';

const siteUrl = BRAND.siteUrl.replace(/\/+$/, '');
if (!/^https:\/\/[^/]+$/.test(siteUrl)) {
  throw new Error(
    `BRAND.siteUrl must be the storefront's https origin, got "${BRAND.siteUrl}"`,
  );
}

const snippet = `{%- comment -%}
  ${BRAND.name}: sends every page of this Online Store theme to the
  storefront at ${siteUrl}, keeping the path (/products/…, /collections/…,
  /cart), the query string and the hash.

  Generated by scripts/shopify-theme-redirect.mjs from BRAND.siteUrl;
  do not edit here, re-run: npm run shopify:redirect

  Install: Online Store → Themes → … → Edit code → Snippets → add
  "headless-redirect", paste this file, then in layout/theme.liquid AND
  layout/password.liquid put  {% render 'headless-redirect' %}  as the first
  line inside <head>.

  Not redirected: the theme editor (so the theme stays editable) and the
  classic customer-account pages. Checkout, order status pages, cart
  permalinks and form posts are served by Shopify itself, not by the theme,
  so they are never affected.
{%- endcomment -%}
{%- unless request.design_mode or template.directory == 'customers' -%}
  {%- assign hs_path = request.path -%}
  {%- if template.name == 'password' -%}{%- assign hs_path = '/' -%}{%- endif -%}
  <meta name="robots" content="noindex">
  <script>
    (function () {
      var site = {{ '${siteUrl}' | json }};
      var root = {{ routes.root_url | json }};
      var path = location.pathname;
      // Shopify Markets language prefix (/en, /fr…): the storefront keeps
      // the language in a cookie, not in the URL.
      if (root !== '/' && path.indexOf(root) === 0) {
        path = path.slice(root.length) || '/';
      }
      var first = path.split('/')[1];
      if (first === 'account' || first === 'challenge') return;
      // The "opening soon" page of a password-protected store.
      if (first === 'password') path = '/';
      document.documentElement.style.visibility = 'hidden';
      location.replace(site + path + location.search + location.hash);
    })();
  </script>
  <noscript><meta http-equiv="refresh" content="0; url=${siteUrl}{{ hs_path | escape }}"></noscript>
{%- endunless -%}
`;

const out = new URL('../shopify/snippets/headless-redirect.liquid', import.meta.url);
await mkdir(new URL('.', out), {recursive: true});
await writeFile(out, snippet);
process.stdout.write(`wrote shopify/snippets/headless-redirect.liquid → ${siteUrl}\n`);
